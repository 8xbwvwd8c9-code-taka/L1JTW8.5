  `mapid` int(5) NOT NULL COMMENT '地圖編號 (-1=全地圖通用掉落池, >0為指定地圖)',
  `itemid` int(10) NOT NULL COMMENT '掉落道具ID',
  `min` int(5) NOT NULL DEFAULT 1 COMMENT '最小掉落數量',
  `max` int(5) NOT NULL DEFAULT 1 COMMENT '最大掉落數量',
  `chance` int(7) NOT NULL DEFAULT 1000000 COMMENT '掉落機率 (基數1,000,000，例如 50000 = 5%)',
  `enchantlvl` int(5) NOT NULL DEFAULT 0 COMMENT '初始強化等級',
  `bless_change` int(3) NOT NULL DEFAULT 0 COMMENT '祝詛狀態機率',
  `note` varchar(100) NOT NULL DEFAULT '' COMMENT '備註說明',
  PRIMARY KEY (`id`),
  KEY `idx_mapid` (`mapid`),
  KEY `idx_itemid` (`itemid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='指定地圖與全地圖掉落表';

